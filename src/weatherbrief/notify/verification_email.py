def send_verification_digest(
    recipients: list[str],
    data: VerificationDigestData,
    *,
    smtp_config: SmtpConfig | None = None,
) -> None:
    """Build and send the verification digest email."""
    if not recipients:
        logger.debug("No recipients for verification digest, skipping")
        return

    label = data.period_label or "Daily"
    subject = f"[FlyFun] Verification Digest — {label}"

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = (
        smtp_config.from_address
        if smtp_config
        else "FlyFun Weather <noreply@flyfun.aero>"
    )
    msg["To"] = ", ".join(recipients)

    msg.attach(MIMEText(_build_digest_plain(data), "plain", "utf-8"))
    msg.attach(MIMEText(_build_digest_html(data), "html", "utf-8"))

    send_message(msg, smtp_config)
    logger.info("Verification digest sent to %d recipient(s)", len(recipients))
