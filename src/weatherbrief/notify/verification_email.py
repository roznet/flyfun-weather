def _build_digest_plain(data: VerificationDigestData) -> str:
    """Render the verification digest as plain text."""
    a = data.activity
    lines: list[str] = []

    label = data.period_label or "Daily"
    lines.append(f"FlyFun Verification Digest — {label}")
    lines.append("=" * 50)
    lines.append("")

    # Activity
    lines.append("ACTIVITY")
    lines.append(f"  Flights verified:  {a.flights_verified}")
    lines.append(f"  Flights completed: {a.flights_completed}")
    lines.append(f"  Airports observed: {a.airports_observed}")
    lines.append(f"  Observations:      {a.observations_collected}")
    lines.append(f"  Cycles:            {a.cycles_run}")
    if a.avg_cycle_duration_ms is not None:
        lines.append(f"  Avg cycle:         {a.avg_cycle_duration_ms:.0f}ms")
    lines.append("")

    # Category accuracy
    lines.append("FLIGHT CATEGORY ACCURACY")
    if data.category_accuracy_today:
        # Build table
        models_set: set[str] = set()
        for r in data.category_accuracy_today:
            models_set.add(r.model)
        models = sorted(m for m in models_set if m != "TAF")
        if "TAF" in models_set:
            models.append("TAF")

        header = f"{'Model':<10}" + "".join(f"{'D-' + str(d):>8}" for d in (0, 1, 2, 3, 5, 7))
        lines.append(header)
        lines.append("-" * len(header))

        today_map = {(r.model, r.days_out): r for r in data.category_accuracy_today}
        for model in models:
            row = f"{model.upper():<10}"
            for d in (0, 1, 2, 3, 5, 7):
                r = today_map.get((model, d))
                if r and r.accuracy_pct is not None:
                    row += f"{r.accuracy_pct:>7.0f}%"
                else:
                    row += f"{'—':>8}"
            lines.append(row)
    else:
        lines.append("  No data available.")
    lines.append("")

    # Notable misses
    if data.notable_misses:
        lines.append("NOTABLE MISSES")
        for m in data.notable_misses:
            ceiling = f" (ceiling {m.ceiling_delta_ft:+.0f}ft)" if m.ceiling_delta_ft is not None else ""
            lines.append(
                f"  {m.icao} {_fmt_time(m.observation_time)} — "
                f"{m.model.upper()}(D-{m.days_out}): {m.model_category}, "
                f"Actual: {m.obs_category}{ceiling}"
            )
        lines.append("")

    # Wind
    if data.wind_advisory:
        lines.append("WIND ADVISORY ACCURACY")
        for w in data.wind_advisory:
            pct = f"{w.accuracy_pct:.0f}%" if w.accuracy_pct is not None else "—"
            lines.append(f"  {w.model.upper():<10} {pct:>6}  (n={w.sample_count})")
        lines.append("")

    if data.missed_warnings:
        lines.append("MISSED WIND WARNINGS")
        for w in data.missed_warnings:
            lines.append(
                f"  {w.icao} {_fmt_time(w.observation_time)} — "
                f"{w.model.upper()}: predicted {w.model_wind_advisory}"
            )
        lines.append("")

    return "\n".join(lines)


