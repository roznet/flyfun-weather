/** Pure decision logic for the stale-pack banner.
 *
 * The banner fires on briefing.html when the loaded pack no longer matches
 * the live flight, i.e. the pilot edited the flight after the pack was
 * generated. It is the ONE place the page explains what is out of date and
 * how to fix it (#987): before that, an altitude edit showed two banners
 * ("Update the advisories… no full refresh needed" and, separately, "Refresh
 * the briefing to regenerate the summary") that read as contradicting each
 * other, because neither said which part of the page it was about.
 *
 * Two parts of a pack go stale on an altitude edit, with two different fixes:
 *  - Route Advisories: re-graded instantly at the new altitude from the saved
 *    forecast (`advisories/recalculate`, the "reanchor" path, #259).
 *  - Synopsis (the AI digest) and the headline sentence: written for the old
 *    altitude, only regenerated by a full refresh (the refresh gate forces a
 *    full run after an edit, #552).
 *
 * Kept in a separate module from briefing-ui.ts so unit tests can
 * import the function without dragging in Leaflet/DOM dependencies.
 */

import type { FlightResponse, RouteAnalysesManifest } from '../store/types';
import { formatAlt, formatDepartureTime } from '../utils';
import { t } from '../i18n/i18n';

/** Sections the banner text links to (their `data-section` key on the page). */
export type BannerLinkSection = 'advisories' | 'synopsis';

/** A piece of banner text: plain text, or a link to a briefing section. */
export type BannerSegment = string | { section: BannerLinkSection; text: string };

export type StalePackBannerKind =
  /** Time or route changed: only a full refresh helps. */
  | 'refresh'
  /** Altitude changed, advisories not yet re-graded. Offers both actions. */
  | 'altitude'
  /** Advisories already re-graded; only the Synopsis is behind. */
  | 'synopsis'
  /** Non-owner: the Synopsis is behind, but they cannot act on it. */
  | 'synopsisInfo';

export interface StalePackBannerState {
  kind: StalePackBannerKind;
  altChanged: boolean;
  timeChanged: boolean;
  /** Altitude changed but time/route didn't → cheap recalc path, not a full refresh. */
  altOnly: boolean;
  /** Show the "Update Route Advisories" (reanchor) button. */
  showUpdate: boolean;
  /** Show the full "Refresh" button. */
  showRefresh: boolean;
  /** Banner text with section links, in reading order. */
  segments: BannerSegment[];
  /** The same text flattened (tests, logs, aria). */
  message: string;
}

const LINK_TOKEN = /\{(advisories|synopsis)\}/;

/** Split a localized string on `{advisories}` / `{synopsis}` into link segments. */
export function toSegments(msg: string): BannerSegment[] {
  const out: BannerSegment[] = [];
  const parts = msg.split(/(\{(?:advisories|synopsis)\})/);
  for (const part of parts) {
    if (!part) continue;
    const m = part.match(LINK_TOKEN);
    if (m && part === m[0]) {
      const section = m[1] as BannerLinkSection;
      out.push({
        section,
        text: t(section === 'advisories' ? 'stalePack.advisoriesLink' : 'stalePack.synopsisLink'),
      });
    } else {
      out.push(part);
    }
  }
  return out;
}

function flatten(segments: BannerSegment[]): string {
  return segments.map(s => (typeof s === 'string' ? s : s.text)).join('');
}

/**
 * @param advisoriesCruiseAltFt altitude the loaded advisories were graded at
 *   (rewritten by the reanchor path, so it can match the flight while the
 *   manifest still carries the old altitude).
 * @param digestCruiseAltFt altitude the pack, and so its Synopsis, was built
 *   for (`snapshot.route.cruise_altitude_ft`; the recalc path never touches it).
 */
export function computeStalePackBanner(
  flight: FlightResponse | null,
  manifest: RouteAnalysesManifest | null,
  isOwner: boolean,
  advisoriesCruiseAltFt?: number | null,
  digestCruiseAltFt?: number | null,
): StalePackBannerState | null {
  if (!flight || !manifest) return null;

  const flightAlt = flight.cruise_altitude_ft;
  // Once the reanchor path has recomputed the advisories at the flight's new
  // altitude, the advisory staleness is resolved even though route_analyses
  // still carries the old altitude.
  const advisoriesResolved =
    advisoriesCruiseAltFt != null && advisoriesCruiseAltFt === flightAlt;
  const altChanged = manifest.cruise_altitude_ft !== flightAlt && !advisoriesResolved;
  const flightDepIso = new Date(flight.departure_time).toISOString();
  const manifestDepIso = new Date(manifest.departure_time).toISOString();
  const timeChanged = flightDepIso !== manifestDepIso;
  const synopsisAlt = digestCruiseAltFt ?? null;
  const synopsisStale = synopsisAlt != null && synopsisAlt !== flightAlt;

  const base = { altChanged, timeChanged, altOnly: altChanged && !timeChanged };

  if (!isOwner) {
    // Non-owners can't refresh or re-grade; they only get told the Synopsis
    // describes another altitude (what the old digest banner told everyone).
    if (!synopsisStale) return null;
    const segments = toSegments(t('stalePack.synopsisInfo', {
      from: formatAlt(synopsisAlt!), to: formatAlt(flightAlt),
    }));
    return { ...base, kind: 'synopsisInfo', showUpdate: false, showRefresh: false, segments, message: flatten(segments) };
  }

  if (timeChanged) {
    // A time/route change genuinely needs a re-fetch: one action, Refresh.
    const parts: string[] = [];
    if (altChanged) {
      parts.push(t('stalePack.altChanged', {
        packAlt: formatAlt(manifest.cruise_altitude_ft),
        flightAlt: formatAlt(flightAlt),
      }));
    }
    parts.push(t('stalePack.timeChanged', {
      packTime: formatDepartureTime(manifest.departure_time),
      flightTime: formatDepartureTime(flight.departure_time),
    }));
    parts.push(t('stalePack.refreshPrompt'));
    const segments = toSegments(parts.join(' '));
    return { ...base, kind: 'refresh', showUpdate: false, showRefresh: true, segments, message: flatten(segments) };
  }

  if (altChanged) {
    // Both fixes on one banner, each saying what it covers.
    const from = formatAlt(synopsisAlt ?? manifest.cruise_altitude_ft);
    const parts = [
      t('stalePack.altitudeChanged', { from: formatAlt(manifest.cruise_altitude_ft), to: formatAlt(flightAlt) }),
      t('stalePack.updateExplain'),
    ];
    if (synopsisStale) parts.push(t('stalePack.synopsisExplain', { from }));
    const segments = toSegments(parts.join(' '));
    return { ...base, kind: 'altitude', showUpdate: true, showRefresh: synopsisStale, segments, message: flatten(segments) };
  }

  if (synopsisStale) {
    // After "Update Route Advisories": say what is current and what is not.
    const segments = toSegments(t('stalePack.synopsisBehind', {
      from: formatAlt(synopsisAlt!), to: formatAlt(flightAlt),
    }));
    return { ...base, kind: 'synopsis', showUpdate: false, showRefresh: true, segments, message: flatten(segments) };
  }

  return null;
}
